package main

import (
	"fmt"
	"io"
	"math"
	"os"
	"regexp"
	"strconv"
	"strings"
)

// The rules, read from the sheet's own cyan defaults and go-pkgx/go-pdfkit:
//
//	base   = the gradient's DARK stop (it carries text and links on white)
//	bright = the gradient's LIGHT stop (accent in dark mode)
//	deep   = base darkened by 39 %   (cyan: #0079A8 -> #054A66 within 5/255)
//	shadow, glow, wash = base at .7, .6, .10;  washDeep = deep at .06
//	chipBg, chipBorder = bright mixed into white at 12 % and 30 %
//	chipFg = deep;  chipBgDark, chipBorderDark = bright at .14 and .32
//	chipFgDark = bright mixed with 45 % white
//
// ⛔ The port has to round as Python rounds and must not let the compiler fuse
// a multiply into an add. kit.py's round() is round-half-to-EVEN, so a channel
// landing on .5 goes to the even neighbour: math.Round would move it up and
// print a different colour. And the Go spec allows x*y+z to become one fused
// instruction on arm64, ppc64 and s390x, which skips a rounding Python does;
// every product below that feeds a sum is therefore wrapped in an explicit
// float64(), the conversion the spec says forces it to be rounded.
//
// Measured, so that the two are not given the same weight: against kit.py on
// 1500 random logos, a mutant rounding half UP differed on 725 and is caught by
// testdata/logos/tie-dark-first.svg; a mutant without the float64() guards
// differed on NONE (darwin/arm64, go1.27.1). The guards are insurance the spec
// calls for, not the fix of an observed difference.

const generator = "go-fleettools/landingkit"

type rgb [3]float64

var white = rgb{255, 255, 255}

func hexRGB(h string) rgb {
	h = strings.TrimPrefix(h, "#")
	var c rgb
	for i := range c {
		v, _ := strconv.ParseUint(h[2*i:2*i+2], 16, 8) // the caller's regexp admits only hex digits
		c[i] = float64(v)
	}
	return c
}

// pyRound is Python 3's round(): half to even.
func pyRound(v float64) int { return int(math.RoundToEven(v)) }

func rgbHex(c rgb) string {
	var b [3]int
	for i, v := range c {
		b[i] = max(0, min(255, pyRound(v)))
	}
	return fmt.Sprintf("#%02x%02x%02x", b[0], b[1], b[2])
}

// mix is c moved a fraction t of the way to other.
func mix(c, other rgb, t float64) rgb {
	var r rgb
	for i := range c {
		r[i] = c[i] + float64((other[i]-c[i])*t)
	}
	return r
}

func rgba(c rgb, a string) string {
	return fmt.Sprintf("rgba(%d,%d,%d,%s)", pyRound(c[0]), pyRound(c[1]), pyRound(c[2]), a)
}

func luminance(c rgb) float64 {
	ch := func(v float64) float64 {
		v /= 255
		if v <= 0.03928 {
			return v / 12.92
		}
		return math.Pow((v+0.055)/1.055, 2.4)
	}
	r, g, b := ch(c[0]), ch(c[1]), ch(c[2])
	return float64(0.2126*r) + float64(0.7152*g) + float64(0.0722*b)
}

func contrast(a, b rgb) float64 {
	la, lb := luminance(a), luminance(b)
	if lb > la {
		la, lb = lb, la
	}
	return (la + 0.05) / (lb + 0.05)
}

var stopColor = regexp.MustCompile(`stop-color="(#[0-9A-Fa-f]{6})"`)

// stops is the logo's gradient as (light, dark): the first two stop colours,
// ordered by luminance. On a tie the second is "light", as in kit.py.
func stops(svg []byte) (light, dark rgb, ok bool) {
	found := stopColor.FindAllSubmatch(svg, 2)
	if len(found) < 2 {
		return light, dark, false
	}
	a, b := hexRGB(string(found[0][1])), hexRGB(string(found[1][1]))
	if luminance(a) > luminance(b) {
		return a, b, true
	}
	return b, a, true
}

type entry struct{ key, value string }

func derive(light, dark rgb) (b []entry, onWhite, onDark float64) {
	base, bright := dark, light
	deep := mix(base, rgb{}, 0.39)
	b = []entry{
		{"base", rgbHex(base)}, {"deep", rgbHex(deep)}, {"bright", rgbHex(bright)},
		{"shadow", rgba(base, ".7")}, {"glow", rgba(base, ".6")},
		{"wash", rgba(base, ".10")}, {"washDeep", rgba(deep, ".06")},
		{"chipBg", rgbHex(mix(white, bright, 0.12))},
		{"chipBorder", rgbHex(mix(white, bright, 0.30))},
		{"chipFg", rgbHex(deep)},
		{"chipBgDark", rgba(bright, ".14")}, {"chipBorderDark", rgba(bright, ".32")},
		{"chipFgDark", rgbHex(mix(bright, white, 0.45))},
	}
	return b, contrast(base, white), contrast(bright, hexRGB("0b0e14"))
}

func brandTOML(b []entry, onWhite, onDark float64, logo string) string {
	var s strings.Builder
	s.WriteString("[params.brand]\n")
	fmt.Fprintf(&s, "# Generated by %s from %s: the colours are\n", generator, logo)
	s.WriteString("# READ from the logo's gradient, never chosen. Do not add other keys:\n")
	s.WriteString("# neutrals (backgrounds, surfaces, greys) belong to the shared sheet.\n")
	fmt.Fprintf(&s, "# Contrast: base on white %.2f:1, bright on the dark background %.2f:1.\n", onWhite, onDark)
	for _, e := range b {
		fmt.Fprintf(&s, "  %s = \"%s\"\n", e.key, e.value)
	}
	return s.String()
}

func cmdBrand(args []string, stdout, stderr io.Writer) int {
	if len(args) != 1 {
		fmt.Fprint(stderr, "usage: landingkit brand <logo.svg>\n")
		return 2
	}
	svg, err := os.ReadFile(args[0])
	if err != nil {
		fmt.Fprintln(stderr, "landingkit:", err)
		return 1
	}
	light, dark, ok := stops(svg)
	if !ok {
		fmt.Fprintf(stderr, "%s: no two-stop gradient found\n", args[0])
		return 1
	}
	b, onWhite, onDark := derive(light, dark)
	fmt.Fprint(stdout, brandTOML(b, onWhite, onDark, args[0]))
	return 0
}
