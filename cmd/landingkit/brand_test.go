// Every testdata/logos/<name>.svg has a <name>.toml beside it that kit.py
// printed (`python3 kit.py brand testdata/logos/<name>.svg`, run from this
// directory, unedited). The Go port must print the same bytes; the only line
// allowed to differ names the generator.
func TestBrandIsByteEqualToKitPy(t *testing.T) {
	logos, err := filepath.Glob("testdata/logos/*.svg")
	if err != nil {
		t.Fatal(err)
	}
	// ⛔ A glob that matched nothing would pass every assertion below.
	if len(logos) < 12 {
		t.Fatalf("found %d logos, want the 10 landings' and the 2 synthetic ones", len(logos))
	}
	for _, logo := range logos {
		want, err := os.ReadFile(strings.TrimSuffix(logo, ".svg") + ".toml")
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Contains(want, []byte("Generated by logos/landing-kit/kit.py from "+logo+":")) {
			t.Fatalf("%s: the golden was not printed by kit.py for this path", logo)
		}
		want = bytes.Replace(want, []byte("logos/landing-kit/kit.py"), []byte(generator), 1)
		var out, errb bytes.Buffer
		if code := run([]string{"brand", logo}, &out, &errb); code != 0 {
			t.Fatalf("%s: exit %d: %s", logo, code, errb.String())
		}
		// kit.py printed every key up to chipFgDark; v0.3.0 appends two lines,
		// checked against a reference that shares no code with derive().
		got, added, ok := strings.Cut(out.String(), "  statsEnd = ")
		if !ok {
			t.Fatalf("%s: no statsEnd line in\n%s", logo, out.String())
		}
		if got != string(want) {
			t.Errorf("%s:\n got:\n%s\nwant (kit.py):\n%s", logo, got, want)
		}
		bright := goldenBright(t, want)
		wantAdded := fmt.Sprintf("\"%s\"\n  bandText = \"%s\"\n  accent = \"%s\"\n  accentDark = \"%s\"\n",
			exactMix(bright, 24), exactMix(bright, 16),
			fittedAccent(t, want, "base", "#ffffff", "#000000"),
			fittedAccent(t, want, "bright", "#"+darkBg, "#ffffff"))
		if added != wantAdded {
			t.Errorf("%s: the appended keys:\n got: statsEnd = %s\nwant: statsEnd = %s", logo, added, wantAdded)
		}
	}
}

// The ties are real: a bright channel that is a multiple of 10 puts chipBorder
// on an exact .5, and Python rounds that to the EVEN neighbour.
// testdata/logos/tie-dark-first.svg holds such a colour, and its golden says
// chipBorder = #b2ffe1, where round-half-up would print #b3ffe1.
func TestPyRoundIsHalfToEven(t *testing.T) {
	for in, want := range map[float64]int{178.5: 178, 179.5: 180, 0.5: 0, 2.4: 2, 2.6: 3} {
		if got := pyRound(in); got != want {
			t.Errorf("pyRound(%v) = %d, want %d", in, got, want)
		}
	}
}

func TestBrandErrors(t *testing.T) {
	dir := t.TempDir()
	one := filepath.Join(dir, "one.svg")
	if err := os.WriteFile(one, []byte(`<stop stop-color="#123456"/>`), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, c := range []struct {
		args []string
		code int
		says string
	}{
		{[]string{"brand"}, 2, "usage: landingkit brand"},
		{[]string{"brand", "a", "b"}, 2, "usage: landingkit brand"},
		{[]string{"brand", filepath.Join(dir, "absent.svg")}, 1, "absent.svg"},
		{[]string{"brand", one}, 1, "one.svg: no two-stop gradient found"},
	} {
		var out, errb bytes.Buffer
		if code := run(c.args, &out, &errb); code != c.code || !strings.Contains(errb.String(), c.says) {
			t.Errorf("%v: exit %d, stderr %q; want %d and %q", c.args, code, errb.String(), c.code, c.says)
		}
		if out.Len() != 0 {
			t.Errorf("%v: printed %q on stdout", c.args, out.String())
		}
	}
}

func TestRun(t *testing.T) {
	for _, c := range []struct {
		args      []string
		code      int
		out, errs string
	}{
		{nil, 2, "", "usage:"},
		{[]string{"help"}, 0, "usage:", ""},
		{[]string{"--help"}, 0, "usage:", ""},
		{[]string{"frobnicate"}, 2, "", `unknown command "frobnicate"`},
	} {
		var out, errb bytes.Buffer
		code := run(c.args, &out, &errb)
		if code != c.code || !strings.Contains(out.String(), c.out) || !strings.Contains(errb.String(), c.errs) {
			t.Errorf("%v: exit %d, stdout %q, stderr %q", c.args, code, out.String(), errb.String())
		}
	}
}

// main is run in-process with os.Exit replaced: no child process is started,
// so this test cannot re-run the suite that contains it.
func TestMain_(t *testing.T) {
	var got = -1
	exit = func(code int) { got = code }
	defer func() { exit = os.Exit }()
	args := os.Args
	defer func() { os.Args = args }()
	os.Args = []string{"landingkit", "brand", "testdata/logos/go-fft.svg"}
	stdout := os.Stdout
	devnull, err := os.Open(os.DevNull)
	if err != nil {
		t.Fatal(err)
	}
	defer devnull.Close()
	os.Stdout = devnull
	main()
	os.Stdout = stdout
	if got != 0 {
		t.Fatalf("main exited %d", got)
	}
}

var goldenBrightRE = regexp.MustCompile(`\n  bright = "#([0-9a-f]{6})"\n`)

// goldenBright is the bright stop as kit.py printed it, so the reference below
// starts from kit.py's reading of the logo and not from stops().
func goldenBright(t *testing.T, golden []byte) [3]int64 {
	t.Helper()
	m := goldenBrightRE.FindSubmatch(golden)
	if m == nil {
		t.Fatalf("no bright in\n%s", golden)
	}
	var c [3]int64
	for i := range c {
		v, err := strconv.ParseInt(string(m[1][2*i:2*i+2]), 16, 64)
		if err != nil {
			t.Fatal(err)
		}
		c[i] = v
	}
	return c
}

// fittedAccent is the reference for the accent keys: the stop named key, as
// kit.py printed it, moved toward away in 4 % steps until it clears 4.5:1 on
// bg — and unmoved when it already does.
//
// It shares no code with derive(). The mix is INTEGER arithmetic: a 4 % step is
// k/25, so a channel is (c*(25-k) + away*k)/25, whose remainder out of 25 can
// never be an exact half — which is the property the 4 % step was chosen for,
// here demonstrated rather than asserted. The luminance is written out from
// WCAG 2.2's own formula instead of calling brand.go's.
func fittedAccent(t *testing.T, golden []byte, key, bg, away string) string {
	t.Helper()
	c, g, a := goldenHex(t, golden, key), parseHex(t, bg), parseHex(t, away)
	lum := func(c [3]int64) float64 {
		var l float64
		for i, w := range [3]float64{0.2126, 0.7152, 0.0722} {
			v := float64(c[i]) / 255
			if v <= 0.03928 {
				v /= 12.92
			} else {
				v = math.Pow((v+0.055)/1.055, 2.4)
			}
			l += w * v
		}
		return l
	}
	ratio := func(x, y [3]int64) float64 {
		hi, lo := lum(x), lum(y)
		if lo > hi {
			hi, lo = lo, hi
		}
		return (hi + 0.05) / (lo + 0.05)
	}
	for k := int64(0); k < 25; k++ {
		var m [3]int64
		for i := range m {
			num := c[i]*(25-k) + a[i]*k
			q, r := num/25, num%25
			if r*2 > 25 {
				q++
			}
			m[i] = q
		}
		if ratio(m, g) >= 4.5 {
			return fmt.Sprintf("#%02x%02x%02x", m[0], m[1], m[2])
		}
	}
	return away
}

func parseHex(t *testing.T, h string) [3]int64 {
	t.Helper()
	h = strings.TrimPrefix(h, "#")
	var c [3]int64
	for i := range c {
		v, err := strconv.ParseInt(h[2*i:2*i+2], 16, 64)
		if err != nil {
			t.Fatal(err)
		}
		c[i] = v
	}
	return c
}

// goldenHex is the colour kit.py printed for key, so the reference starts from
// kit.py's reading of the logo and not from stops().
func goldenHex(t *testing.T, golden []byte, key string) [3]int64 {
	t.Helper()
	m := regexp.MustCompile(`\n  ` + key + ` = "(#[0-9a-f]{6})"\n`).FindSubmatch(golden)
	if m == nil {
		t.Fatalf("no %s in\n%s", key, golden)
	}
	return parseHex(t, string(m[1]))
}

// exactMix is bright mixed into white at pct %, in integer arithmetic: the
// channel is (255*(100-pct) + b*pct) / 100, rounded half to even on the exact
// remainder (or half up). No float64 and no call into brand.go, so it cannot
// share a mistake with derive().
func exactMix(bright [3]int64, pct int64, halfUp ...bool) string {
	s := "#"
	for _, b := range bright {
		num := 255*(100-pct) + b*pct
		q, r := num/100, num%100
		if r > 50 || (r == 50 && (q%2 == 1 || len(halfUp) > 0)) {
			q++
		}
		s += fmt.Sprintf("%02x", q)
	}
	return s
}

// For EVERY channel value, not only the logos': derive's rule agrees with
// exact arithmetic, and at 24 % and 16 % it agrees with rounding half UP too,
// because no channel lands on a tie. The witness: at 30 % (chipBorder's
// fraction) ties exist, and the two rounding modes must be seen to disagree,
// or the half-up comparison could not see a tie at all.
func TestNewKeysMatchExactArithmetic(t *testing.T) {
	differ := func(pct int64, halfUp bool) (bad []int) {
		for v := range 256 {
			c := [3]int64{int64(v), int64(v), int64(v)}
			want := exactMix(c, pct)
			if halfUp {
				want = exactMix(c, pct, true)
			}
			if rgbHex(mix(white, rgb{float64(v), float64(v), float64(v)}, float64(pct)/100)) != want {
				bad = append(bad, v)
			}
		}
		return bad
	}
	if bad := differ(30, true); len(bad) == 0 {
		t.Fatal("witness: at 30 % rounding half up never differs; the tie check is blind")
	}
	for _, pct := range []int64{24, 16} {
		for _, up := range []bool{false, true} {
			if bad := differ(pct, up); len(bad) != 0 {
				t.Errorf("at %d %% (half up: %v), derive's rule differs on channel values %v", pct, up, bad)
			}
		}
	}
	if statsEndT != 0.24 || bandTextT != 0.16 {
		t.Fatalf("the fractions moved to %v and %v; the README and the test above name 24 and 16", statsEndT, bandTextT)
	}
}
